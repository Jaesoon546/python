-- DEPT, EMP, BONUS, SALGRADE 테이블 생성 및 샘플 데이터 입력

CREATE TABLE DEPT( -- 부서
DEPTNO TINYINT PRIMARY KEY, -- 부서번호
 DNAME VARCHAR(14) , -- 부서이름
 LOC VARCHAR(13) -- 위치
) ;

CREATE TABLE EMP(
EMPNO SMALLINT PRIMARY KEY, -- 사원번호
 ENAME VARCHAR(10), -- 사원이름
 JOB VARCHAR(9), -- 업무
 MGR SMALLINT, -- 관리자
 HIREDATE DATE, -- 채용일
SAL FLOAT, -- 급여
COMM FLOAT, -- 커미션
 DEPTNO TINYINT , -- 부서번호
 foreign key(DEPTNO) references DEPT(DEPTNO)
);

CREATE TABLE BONUS(
 ENAME VARCHAR(10) , -- 사원이름
 JOB VARCHAR(9) , -- 업무
 SAL INT, -- 급여
COMM INT -- 커미션
) ;



CREATE TABLE SALGRADE(
GRADE TINYINT, -- 등급
 LOSAL SMALLINT, -- 급여의 하한값
HISAL SMALLINT -- 급여의 상한값
);
